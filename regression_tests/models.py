from datetime import datetime
from enum import StrEnum

from pydantic import BaseModel, ConfigDict
from sqlalchemy import JSON, Column
from sqlmodel import Field, SQLModel

from core.config import now
from core.ids import new_id


class SourceConversation(SQLModel, table=True):
    id: str = Field(default_factory=new_id, primary_key=True)
    transcript: str
    reported_issue: str | None = None
    agent_version: str | None = None
    created_at: datetime = Field(default_factory=now)


class TestSpec(BaseModel):
    # An unknown field is a typo or a model mistake, never something to drop silently.
    model_config = ConfigDict(extra="forbid")

    goal: str
    facts: dict[str, str]
    behavior: str
    policy_under_test: str
    expected_outcome: str


class TestStatus(StrEnum):
    DRAFT = "draft"
    READY = "ready"


class Test(SQLModel, table=True):
    id: str = Field(default_factory=new_id, primary_key=True)
    lineage_id: str
    name: str
    version: int = 1
    # None for generated tests, which have no recorded call behind them.
    source_conversation_id: str | None = Field(
        default=None, foreign_key="sourceconversation.id"
    )
    # Set for tests generated by a swarm; plain id, so this module needn't import swarms.
    swarm_id: str | None = Field(default=None, index=True)
    # Set when a swarm test was promoted into the regression suite: where it came from.
    promoted_from_swarm_id: str | None = None
    status: TestStatus = TestStatus.DRAFT
    spec: dict = Field(sa_column=Column(JSON))
    inferred: dict | None = Field(sa_column=Column(JSON))
    created_at: datetime = Field(default_factory=now)
